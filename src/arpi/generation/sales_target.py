def _check_scope_identity(frame: pd.DataFrame) -> CheckResult:
    """``DQ-TGT-006`` -- the scope identity columns agree with the scope type."""
    base = _target_result(
        CHECK_TARGET_SCOPE_IDENTITY,
        "fact_sales_target scope identity matches its scope type",
        CHECK_CATEGORY_COMPLETENESS,
    )
    problems = 0
    for row in frame.itertuples(index=False):
        scope_type = str(row.target_scope_type)
        scope_id = row.target_scope_id
        department = row.department_name
        employee = row.employee_id
        blank_scope_id = scope_id is None or pd.isna(scope_id) or str(scope_id).strip() == ""
        has_department = department is not None and not pd.isna(department)
        has_employee = employee is not None and not pd.isna(employee)
        if blank_scope_id:
            problems += 1
            continue
        contradictions = {
            TARGET_SCOPE_STORE: has_department
            or has_employee
            or str(scope_id) != str(row.dealership_id),
            TARGET_SCOPE_DEPARTMENT: not has_department
            or has_employee
            or str(department) != str(scope_id),
            TARGET_SCOPE_EMPLOYEE: has_department
            or not has_employee
            or str(employee) != str(scope_id),
        }
        if contradictions.get(scope_type, True):
            problems += 1
    if problems == 0:
        return base
    return base.failed(
        f"{problems} row(s) carry a scope identity that contradicts their scope type.",
        observed_value=float(problems),
        failed_record_count=problems,
    )


def _check_kpi_vocabulary(frame: pd.DataFrame) -> CheckResult:
    """``DQ-TGT-007`` -- the targeted metric is one the domain supports for its scope."""
    base = _target_result(
        CHECK_TARGET_KPI_VOCABULARY,
        "fact_sales_target.kpi_id names a supported target metric",
        CHECK_CATEGORY_BUSINESS_RULE,
    )
    problems = 0
    for row in frame.itertuples(index=False):
        kpi_id = str(row.kpi_id)
        scope_type = str(row.target_scope_type)
        if kpi_id not in TARGET_METRIC_KPI_IDS:
            problems += 1
            continue
        allowed = TARGET_SCOPE_METRICS.get(scope_type, ())
        if kpi_id not in allowed:
            problems += 1
    if problems == 0:
        return base
    return base.failed(
        f"{problems} row(s) target a metric their scope does not own; the supported "
        f"vocabulary is {TARGET_SCOPE_METRICS}.",
        observed_value=float(problems),
        failed_record_count=problems,
    )


