# Generation
# ---------------------------------------------------------------------------------------
@dataclass(frozen=True, slots=True)
class PlannedMonth:
    """One store-month's planning frame, before any target row is emitted.

    Attributes:
        dealership_id: The store the plan belongs to.
        month_start: First day of the planned month.
        selling_days: Governed selling days in the month, from ``dim_date``.
    """

    dealership_id: str
    month_start: date
    selling_days: int


def _planning_frame(config: ArpiConfig) -> tuple[PlannedMonth, ...]:
    """Build the exogenous planning frame: every store-month, with its selling days.

    The selling-day count is rebuilt from :func:`build_calendar_rows`, which is the one
    implementation of the ADR-0002 selling-day rule. No second calendar is defined here.

    Args:
        config: Resolved configuration supplying the reporting window.

    Returns:
        One :class:`PlannedMonth` per active store per month in the window, ordered by
        store then month.
    """
    calendar = build_calendar_rows(config.reporting.start_date, config.reporting.end_date)
    selling_days_by_month: dict[date, int] = {}
    for month_start, is_selling_day in zip(
        calendar["month_start_date"], calendar["is_selling_day"], strict=True
    ):
        key = month_start.date() if isinstance(month_start, pd.Timestamp) else month_start
        selling_days_by_month[key] = selling_days_by_month.get(key, 0) + int(bool(is_selling_day))

    months = sorted(selling_days_by_month)
    stores = sorted(
        (store for store in STORE_DEFINITIONS if store.is_active),
        key=lambda store: store.dealership_id,
    )
    return tuple(
        PlannedMonth(
            dealership_id=store.dealership_id,
            month_start=month,
            selling_days=selling_days_by_month[month],
        )
        for store in stores
        for month in months
    )


def _variation(rng: random.Random, half_width: float) -> Decimal:
    """Draw one bounded planning variation as an exact multiplier.

    Args:
        rng: The entity's dedicated generator.
        half_width: Half-width of the uniform draw, as a fraction of 1.

    Returns:
        ``1 + u`` where ``u`` is uniform on ``[-half_width, +half_width]``, quantized to
        six places so the multiplier itself is exact before it touches money.
    """
    drawn = rng.uniform(-half_width, half_width)
    return (Decimal(1) + Decimal(repr(drawn))).quantize(
        Decimal("0.000001"), rounding=ROUND_HALF_EVEN
    )


def _whole_units(value: Decimal) -> Decimal:
    """Quantize a planned unit count to whole units, carried at cent scale.

    Units are whole: a store does not commit to 57.4 deliveries. The value is
    nevertheless carried in ``numeric(14,2)`` alongside currency targets, so it is
    rendered as ``57.00`` rather than ``57``.

    Args:
        value: The unrounded planned unit count.

    Returns:
        The value rounded half-up to a whole number and restated at cent scale.
    """
    return value.quantize(_WHOLE, rounding=ROUND_HALF_UP).quantize(_CENTS)


def _money(value: Decimal) -> Decimal:
    """Quantize a planned money value to the cent, half-up."""
    return value.quantize(_CENTS, rounding=ROUND_HALF_UP)


class SalesTargetGenerator(BaseGenerator):
    """Build the monthly operating plan for every store in the reporting window."""

    entity_name = ENTITY_SALES_TARGET
    declared_columns = SALES_TARGET_COLUMNS
    namespace = SALES_TARGET_NAMESPACE

    def build_frame(self, config: ArpiConfig) -> pd.DataFrame:
        """Build the sales-target frame.

        Args:
            config: Resolved configuration supplying the master seed and the window.

        Returns:
            A frame with the eleven contract columns, in order, ordered by store, month,
            scope type, scope id and KPI so the output is byte-stable.

        Raises:
            GenerationError: If a store in the window has no planning baseline. A store
                with no plan would silently produce no targets, which is
                indistinguishable from a store that missed its plan.
        """
        rng = rng_for(config.random_seed, SALES_TARGET_NAMESPACE)
        records: list[dict[str, Any]] = []

        for planned in _planning_frame(config):
            baseline = STORE_PLANNING_BASELINE.get(planned.dealership_id)
            if baseline is None:
                raise GenerationError(
                    f"Store {planned.dealership_id!r} has no entry in "
                    "arpi.generation.sales_target.STORE_PLANNING_BASELINE, so no "
                    "operating plan can be written for it. Add the store's planning "
                    "baseline rather than letting it generate no targets.",
                    entity=ENTITY_SALES_TARGET,
                    dealership_id=planned.dealership_id,
                )
            records.extend(_store_month_rows(rng, planned, baseline))

        frame = pd.DataFrame.from_records(records, columns=list(SALES_TARGET_COLUMNS))
        frame = frame.sort_values(
            by=[
                "dealership_id",
                "target_month_date_key",
                "target_scope_type",
                "target_scope_id",
                "kpi_id",
            ],
            kind="stable",
            ignore_index=True,
        )
        frame["sales_target_id"] = [f"TGT-{ordinal:08d}" for ordinal in range(1, len(frame) + 1)]
        return frame.astype(SALES_TARGET_DTYPES)


def _store_month_rows(
    rng: random.Random,
    planned: PlannedMonth,
    baseline: StorePlanningBaseline,
) -> list[dict[str, Any]]:
    """Emit every target row for one store-month.

    Four rows: the store's unit target and total-gross target, and the two department
    gross targets that partition the store's total-gross target exactly.

    Args:
        rng: The entity's dedicated generator. Consumed in a fixed order, so the output
            is stable for a given seed.
        planned: The store-month planning frame.
        baseline: The store's exogenous planning assumptions.

    Returns:
        Four record dictionaries, without ``sales_target_id`` (assigned after sorting).
    """
    month_key = date_key(planned.month_start)
    unit_variation = _variation(rng, TARGET_PLANNING_VARIATION)
    gross_variation = _variation(rng, TARGET_GROSS_VARIATION)

    seasonality = Decimal(repr(TARGET_MONTH_SEASONALITY[planned.month_start.month]))
    per_day = Decimal(repr(baseline.units_per_selling_day))
    unit_target = _whole_units(
        per_day * Decimal(planned.selling_days) * seasonality * unit_variation
    )

    gross_target = _money(unit_target * baseline.planned_total_gross_per_unit * gross_variation)
    # The Sales department's share is struck first and Finance carries the remainder, so
    # the two department targets sum to the store target to the cent by construction
    # rather than by a rounding coincidence.
    front_target = _money(gross_target * baseline.planned_front_gross_share)
    back_target = gross_target - front_target

    rows = [
        _row(
            planned,
            month_key,
            scope_type=TARGET_SCOPE_STORE,
            scope_id=planned.dealership_id,
            department_name=None,
            kpi_id="KPI-SLS-001",
            target_value=unit_target,
            stretch_value=_whole_units(unit_target * STRETCH_TARGET_MULTIPLIER),
        ),
        _row(
            planned,
            month_key,
            scope_type=TARGET_SCOPE_STORE,
            scope_id=planned.dealership_id,
            department_name=None,
            kpi_id="KPI-GRS-003",
            target_value=gross_target,
            stretch_value=_money(gross_target * STRETCH_TARGET_MULTIPLIER),
        ),
    ]
    for department, (kpi_id, value) in (
        ("Sales", (TARGET_DEPARTMENT_METRIC["Sales"], front_target)),
        ("Finance", (TARGET_DEPARTMENT_METRIC["Finance"], back_target)),
    ):
        rows.append(
            _row(
                planned,
                month_key,
                scope_type=TARGET_SCOPE_DEPARTMENT,
                scope_id=department,
                department_name=department,
                kpi_id=kpi_id,
                target_value=value,
                stretch_value=_money(value * STRETCH_TARGET_MULTIPLIER),
            )
        )
    return rows


def _row(
    planned: PlannedMonth,
    month_key: int,
    *,
    scope_type: str,
    scope_id: str,
    department_name: str | None,
    kpi_id: str,
    target_value: Decimal,
    stretch_value: Decimal,
) -> dict[str, Any]:
    """Assemble one target record."""
    return {
        "sales_target_id": None,
        "target_month_date_key": month_key,
        "dealership_id": planned.dealership_id,
        "target_scope_type": scope_type,
        "target_scope_id": scope_id,
        "department_name": department_name,
        # DASH.5 generates no employee-scope target. The column exists because the
        # scope vocabulary is permanent; see the module docstring.
        "employee_id": None,
        "kpi_id": kpi_id,
        "target_value": target_value,
        "stretch_target_value": stretch_value,
        "source_system": SOURCE_SYSTEM,
    }


