def _check_exact_precision(frame: pd.DataFrame) -> CheckResult:
    """``DQ-TGT-011`` -- every value is a ``Decimal`` with at most two decimal places."""
    base = _target_result(
        CHECK_TARGET_EXACT_PRECISION,
        "fact_sales_target values are exact to two decimal places",
        CHECK_CATEGORY_BUSINESS_RULE,
    )
    offending = 0
    for column in ("target_value", "stretch_target_value"):
        for value in frame[column]:
            if not isinstance(value, Decimal):
                offending += 1
                continue
            exponent = value.as_tuple().exponent
            # A non-integer exponent means NaN or Infinity, which is not a target either.
            if not isinstance(exponent, int) or -exponent > _MAX_SCALE:
                offending += 1
    if offending == 0:
        return base
    return base.failed(
        f"{offending} value(s) are not exact Decimals quantized to the cent. A binary "
        "float in a target makes its attainment denominator irreproducible.",
        observed_value=float(offending),
        failed_record_count=offending,
    )


def _check_department_split_sums(frame: pd.DataFrame) -> CheckResult:
    """``DQ-TGT-012`` -- department gross targets partition the store gross target."""
    base = _target_result(
        CHECK_TARGET_DEPARTMENT_SPLIT_SUMS,
        "department gross targets sum exactly to the store total-gross target",
        CHECK_CATEGORY_BUSINESS_RULE,
    )
    store_gross: dict[tuple[str, str], Decimal] = {}
    department_gross: dict[tuple[str, str], Decimal] = {}
    for row in frame.itertuples(index=False):
        key = (str(row.dealership_id), str(row.target_month_date_key))
        value = Decimal(str(row.target_value))
        if str(row.target_scope_type) == TARGET_SCOPE_STORE and str(row.kpi_id) == "KPI-GRS-003":
            store_gross[key] = store_gross.get(key, Decimal(0)) + value
        elif str(row.target_scope_type) == TARGET_SCOPE_DEPARTMENT:
            department_gross[key] = department_gross.get(key, Decimal(0)) + value

    mismatched = sorted(
        f"{store}/{month}"
        for (store, month), total in store_gross.items()
        if department_gross.get((store, month), Decimal(0)) != total
    )
    if not mismatched:
        return base
    return base.failed(
        f"{len(mismatched)} store-month(s) whose department gross targets do not sum to "
        f"the store total-gross target: {', '.join(mismatched[:5])}.",
        observed_value=float(len(mismatched)),
        failed_record_count=len(mismatched),
    )


