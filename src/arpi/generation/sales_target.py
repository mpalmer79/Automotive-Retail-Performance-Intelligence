"""Generator for ``warehouse.fact_sales_target`` -- the operating plan, not the result.

WHAT THIS ENTITY IS
-------------------
One row per store, per governed target scope, per targeted KPI, per calendar month,
carrying the month's committed goal (``target_value``) and its stretch goal
(``stretch_target_value``). It is the first management-planning domain in ARPI and it
is promoted by delivery increment ``DASH.5``.

Every value here is a **synthetic internal operating goal for the fictional Granite Auto
Group**. It is not an industry benchmark, not a manufacturer objective, not a market
standard and not a real dealership's plan. Nothing in this module may be read as
"good", "average" or "recommended".

THE RULE THAT SHAPES THE WHOLE MODULE: NO OUTCOME LEAKAGE
---------------------------------------------------------
A plan that is computed from the result it is supposed to measure is not a plan. If
this module read ``sale_event`` and emitted ``actual * 1.05``, every attainment figure
on the console would be a restatement of the same number and the demonstration would
be worthless -- worse, it would be dishonest, because the page would present a
tautology as a management measurement.

So this module **must not import, call, or otherwise consume any realized sales
output**. Its inputs are exogenous planning assumptions only:

  * the store's operating model and planning scale (:data:`STORE_PLANNING_BASELINE`),
    the same class of fixed store-scale assumption ``arpi.generation.vehicle`` uses;
  * the governed selling-day calendar, rebuilt from :func:`build_calendar_rows`, which
    is deterministic, seed-free and owned by ADR-0002;
  * a planning seasonality shape (:data:`TARGET_MONTH_SEASONALITY`) declared here as a
    project default;
  * seeded planning variation drawn from the ARPI master seed through
    :func:`arpi.utilities.seeding.rng_for`.

``tests/unit/test_sales_target_generation.py`` asserts the module's import graph
contains no realized-sales module, so the rule is enforced rather than promised.

THE SCOPE MODEL, AND WHY DEPARTMENTS TARGET GROSS COMPONENTS
------------------------------------------------------------
``SQ-31`` asks whether the group is hitting its targets *by store and by department*,
so the scope model has to answer both halves without double counting.

  * **Store scope** targets the two headline store measures: retail units
    (``KPI-SLS-001``) and total gross (``KPI-GRS-003``).
  * **Department scope** targets the two *components* of total gross, which partition
    it exactly: the Sales department owns front-end gross (``KPI-GRS-001``) and the
    Finance department owns back-end gross (``KPI-GRS-002``). ``fact_vehicle_sale``
    enforces ``total_gross = front_end_gross + back_end_gross`` as a CHECK constraint,
    so the two department actuals sum to the store actual with no overlap and no gap.
    The generator makes the two department *targets* sum to the store total-gross
    target for the same reason.
  * **Retail units are deliberately store-scope only.** A retail unit is delivered
    once. Attributing it to the Sales department reproduces the store target, and
    attributing it to Finance as well would count the same car twice. Dealership
    practice is the same: F&I measures are computed *per* the sales department's unit
    count, not on a second unit count of their own.
  * **Employee scope** is part of the permanent vocabulary and is physically supported
    by ``warehouse.fact_sales_target`` (nullable ``employee_key``, CHECK-coupled to the
    scope type, foreign key to ``warehouse.dim_employee``). It is **not generated by
    DASH.5**: no registered stakeholder question requires employee-scope targets,
    ``DASH.11`` owns the employee-performance surface, and Gate 4 forbids adding data a
    question does not require. The decision is recorded in
    ``docs/source-to-target/STM-016-fact-sales-target.md`` section 6.

EXACT ARITHMETIC
----------------
Every emitted money and unit value is a :class:`decimal.Decimal` quantized to two
places. No Python float ever touches a target: the planning multipliers are floats
because they are dimensionless shape parameters, but they are converted to
``Decimal`` before they multiply a currency or a unit count, and the result is
quantized with :data:`decimal.ROUND_HALF_UP` exactly once.
"""

