export interface ApplicationImageProps {
  /** Path under `public/`, produced by `scripts/capture-product-media.ts`. */
  src: string
  /**
   * What the capture shows, for a reader who cannot see it. Never "screenshot of
   * the inventory explorer": describe what is on screen.
   */
  alt: string
  /** The captured pixel dimensions. Required, so the box is reserved. */
  width: number
  height: number
  className?: string
}

/**
 * A captured route, sized so it reserves its own space.
 *
 * WHY A PLAIN `<img>` AND NOT `next/image`
 * ----------------------------------------
 * `next/image` earns its keep when it can resize a source into several
 * candidates and serve the smallest one that fits. These four files are already
 * the only size they are ever displayed at, already WebP, and already under
 * 120 kB each. Routing them through the optimizer would add a runtime dependency
 * on `sharp` inside the Railway standalone image - which `next.config.ts`
 * deliberately does not configure a loader for - in exchange for nothing.
 *
 * The two things `next/image` is genuinely for are done here explicitly:
 * `width` and `height` are intrinsic, so the box is reserved and the frame
 * causes no layout shift; and `loading="lazy"` keeps every capture off the
 * critical path, because none of them is above the fold.
 */
export function ApplicationImage({
  src,
  alt,
  width,
  height,
  className,
}: ApplicationImageProps) {
  return (
    /* Pre-sized, pre-encoded WebP served without the optimizer on purpose. The
       reasoning is in the doc comment above; the intrinsic dimensions and the
       lazy attribute do the two jobs `next/image` would have done here. */
    // eslint-disable-next-line @next/next/no-img-element
    <img
      src={src}
      alt={alt}
      width={width}
      height={height}
      loading="lazy"
      decoding="async"
      className={cx('block h-auto w-full bg-surface-sunken', className)}
    />
  )
}
